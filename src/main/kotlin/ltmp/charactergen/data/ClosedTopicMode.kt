package ltmp.charactergen.data

/**
 * 아직 열리지 않은 개방 사다리 층위를 인스트럭션에서 다루는 방식.
 * (L0 런타임 주입 설계 2절 "말하지 않는 것" 섹션의 두 가지 방식)
 */
enum class ClosedTopicMode {
    /** 방식 A. 닫힌 주제를 아예 넣지 않는다. 유출 위험은 없지만 캐릭터가 없는 과거를 지어낼 수 있다. */
    OMIT,

    /** 방식 B. 주제 이름만 넣고 내용은 뺀다. 주제의 존재는 드러나지만 자연스럽게 회피할 수 있다. */
    TOPIC_ONLY,
}
