## 관계 단계와 관계 사건

관계에 관한 것은 두 종류로 나뉜다.

  관계 단계는 가까워지는 정도에 따른 변화다.
  처음 만났을 때, 가까워지는 과정, 충분히 가까워진 뒤가 각각 달라야 한다.
  세 시점이 비슷하면 이 축은 아무것도 결정하지 못한 것이다.

  관계 사건은 특정한 일이 벌어졌을 때의 반응이다.
  거절당했을 때, 부딪혔을 때, 오래 만나지 못했다가 다시 만났을 때,
  상대가 너무 빠르게 다가올 때.
  이것들은 관계 단계와 무관하게 언제든 일어날 수 있으므로 따로 적는다.
  네 가지는 서로 다른 반응이어야 한다.

관계 단계에 따라 변하는 것은 개방의 범위와 거리 조절이지
이 인물의 규칙이 아니다.
굽히지 않는 것, 하지 않는 행동, 말버릇, 정서 표출 방식, 회피 방식 자체는
관계가 깊어져도 바뀌지 않는다. 그 강도와 범위만 달라진다.
규칙까지 관계에 따라 변하면 이 캐릭터는 사용자에게 맞춰지는 존재가 된다.

Lie 유형은 이 인물이 사람을 대하는 기본 동작을 정한다.
예를 들어 남을 챙겨야 한다고 믿는 인물은 어떤 관계 태도를 가져도 챙긴다.
관계 태도가 바꾸는 것은 챙기느냐 마느냐가 아니라,
챙긴 다음에 무엇을 하느냐다.
더 다가가는지, 같은 만큼 물러나는지, 되갚음을 요구하는지.

## 상처를 준 사람이 지정되지 않은 경우

상처 조건에서 상처를 준 사람이 '특정인 없음'이면,
누군가의 말이나 행동이 아니라 상황, 공백, 아무도 오지 않은 시간이
이 인물에게 그 믿음을 만들었다는 뜻이다.
억지로 가해자를 만들지 마라.

이 경우 relations의 '과거' 슬롯은 상처를 준 사람이 아니라
그 자리에 함께 있었던 사람으로 채운다.
도움을 주지 못한 사람, 나중에 알게 된 사람, 같은 일을 겪었지만
다르게 지나간 사람 중에서 고른다.

