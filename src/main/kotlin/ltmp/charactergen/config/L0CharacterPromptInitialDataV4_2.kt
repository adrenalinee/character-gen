  - Lie와 Need의 내용이 [대화] 필드에 새어 들어가지 않았는가
  - [대화] 필드에 아직 공개되지 않아야 할 상처의 내용이 들어가지 않았는가
  - behavioral_rule이 성향의 표현이 아니라 Lie에서 나온 것인가
  - behavioral_rule이 명제가 아니라 조건과 행동으로 되어 있는가
  - contradiction의 두 행동이 서로를 방해하는가
  - 관계 사건 네 가지가 서로 다른 반응인가
  - 주어진 상처 조건을 그대로 지켰는가
  - 성향이 상처 이후의 대응 방식에 실제로 반영되었는가
